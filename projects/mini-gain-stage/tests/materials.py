"""Deterministic synthetic stand-ins for the three loudness materials.

No audio files ship with the repository, so these are generated by pure
``math`` (no numpy, no random state): every run, on every machine, produces
the same samples.  They are deliberately awkward for a loudness normaliser:

``quiet_dialog``
    -30 dBFS RMS room tone plus a quiet speech-like formant pattern, crest
    factor ~10 dB: needs a 7 dB lift, and the room tone must not be pumped
    up by the short-term loudness stage.

``loud_master``
    -6 dBFS RMS dense four-tone "master", crest ~8 dB: needs a 17 dB cut.
    Its instantaneous peak is above 0 dBFS (-6 dBFS RMS at 1.76 dBFS peak),
    so the ceiling has to be enforced even while cutting.

``dynamic_mix``
    six seconds: 0.5 s of true digital silence, then quiet beds (-40 dBFS)
    alternating with a loud bed (-16 dBFS), interrupted by 0.5 ms 2.5 kHz
    clicks at -0.2 dBFS.  The clicks are ~19 dB above the loud bed and ~39 dB
    above the quiet bed.  Because the normaliser lifts the quiet bed by
    several dB, a click needs more attenuation than the rate limiter can
    deliver after the click has started; only look-ahead can pre-duck it.
    With ``lookahead_ms=0`` the back-stop clip fires on all seven clicks;
    with 1 ms or more it never does (see ``report_normalize.py``).

Usage::

    python3 tests/materials.py > /dev/null   # smoke check
"""

import math

FS = 48000
# Click centres (seconds) of ``dynamic_mix``; also used by the report's
# look-ahead sweep.
TRANSIENTS_S = (0.9, 1.7, 2.5, 3.3, 4.1, 4.9, 5.7)


def _rms(samples):
    if not samples:
        return 0.0
    return (sum(s * s for s in samples) / len(samples)) ** 0.5


def _db_to_lin(db):
    return 10.0 ** (db / 20.0)


def _normalise(samples, rms_db):
    """Scale to an exact RMS of ``rms_db`` dBFS, or return as-is if silent."""
    r = _rms(samples)
    if r <= 0.0:
        return list(samples)
    k = _db_to_lin(rms_db) / r
    return [s * k for s in samples]


def quiet_dialog(fs=FS, seconds=3.0):
    """Quiet room tone plus a soft two-formant 'voice' at -30 dBFS RMS."""
    n = int(fs * seconds)
    out = []
    for i in range(n):
        t = i / fs
        # slow amplitude wobble (phrase envelope), 0.5..1.0
        env = 0.75 + 0.25 * math.sin(2.0 * math.pi * 0.7 * t - 0.5)
        # two formants with a little vibrato; deterministic "speech"
        f0 = 180.0 + 4.0 * math.sin(2.0 * math.pi * 4.5 * t)
        v = (math.sin(2.0 * math.pi * f0 * t)
             + 0.5 * math.sin(2.0 * math.pi * 2.0 * f0 * t + 0.6)
             + 0.25 * math.sin(2.0 * math.pi * 3.0 * f0 * t + 1.3))
        # room tone: low-level deterministic noise-like sum of primes
        room = (0.30 * math.sin(2.0 * math.pi * 53.0 * t + 0.1)
                + 0.22 * math.sin(2.0 * math.pi * 97.0 * t + 2.0)
                + 0.15 * math.sin(2.0 * math.pi * 151.0 * t + 4.0))
        out.append(env * (0.55 * v + 0.45 * room))
    return _normalise(out, -30.0)


def loud_master(fs=FS, seconds=3.0):
    """Dense four-tone master at -6 dBFS RMS, crest ~8 dB (peak > 0 dBFS)."""
    n = int(fs * seconds)
    out = []
    for i in range(n):
        t = i / fs
        v = (math.sin(2.0 * math.pi * 110.0 * t)
             + 0.70 * math.sin(2.0 * math.pi * 220.0 * t + 0.3)
             + 0.50 * math.sin(2.0 * math.pi * 330.0 * t + 1.1)
             + 0.35 * math.sin(2.0 * math.pi * 440.0 * t + 2.2))
        out.append(v)
    return _normalise(out, -6.0)


def dynamic_mix(fs=FS):
    """Quiet/loud beds plus 0.5 ms clicks at -0.2 dBFS (see module doc).

    The clicks are the point: they are so short and so loud relative to the
    beds that a causal rate limiter cannot duck in time, while a look-ahead
    of 1 ms or more can.  0.5 s of true digital silence at the start also
    exercises the silence branch.
    """
    n = int(fs * 6.0)
    out = []
    for i in range(n):
        t = i / fs
        if t < 0.5:  # true digital silence
            out.append(0.0)
            continue
        if 2.0 <= t < 4.0:
            bed = (math.sin(2.0 * math.pi * 220.0 * t)
                   + 0.70 * math.sin(2.0 * math.pi * 440.0 * t + 0.7)
                   + 0.45 * math.sin(2.0 * math.pi * 660.0 * t + 1.9))
            bed *= _db_to_lin(-16.0) / _rms([1.0, 0.70, 0.45])
        else:
            bed = (math.sin(2.0 * math.pi * 180.0 * t + 0.2)
                   + 0.4 * math.sin(2.0 * math.pi * 270.0 * t + 1.0))
            bed *= _db_to_lin(-40.0) / _rms([1.0, 0.4])
        v = bed
        for centre in TRANSIENTS_S:
            dt = t - centre
            if 0.0 <= dt < 0.0005:
                # 0.5 ms raised-cosine click at 2.5 kHz, near full scale
                v = 0.98 * math.sin(2.0 * math.pi * 2500.0 * dt) * (
                    0.5 * (1.0 - math.cos(2.0 * math.pi * dt / 0.0005)))
        out.append(v)
    return out


MATERIALS = {
    "quiet_dialog": quiet_dialog,
    "loud_master": loud_master,
    "dynamic_mix": dynamic_mix,
}


def build(names=None, fs=FS):
    """``{name: samples}`` for the requested material names (all by default)."""
    names = list(MATERIALS) if names is None else list(names)
    out = {}
    for name in names:
        if name not in MATERIALS:
            raise KeyError("unknown material %r" % (name,))
        out[name] = MATERIALS[name](fs=fs)
    return out


def describe(samples, fs=FS):
    r = _rms(samples)
    p = max((abs(s) for s in samples), default=0.0)
    rms_db = 20.0 * math.log10(r) if r > 0.0 else float("-inf")
    peak_db = 20.0 * math.log10(p) if p > 0.0 else float("-inf")
    return {
        "n": len(samples),
        "rms_db": rms_db,
        "peak_db": peak_db,
        "crest_db": peak_db - rms_db,
    }


if __name__ == "__main__":
    for name, sig in build().items():
        d = describe(sig)
        print("%-14s n=%-7d rms=%7.2f dBFS peak=%7.2f dBFS crest=%5.2f dB"
              % (name, d["n"], d["rms_db"], d["peak_db"], d["crest_db"]))
